/** The width of a text in the pixel font, or 0 when it has a letter the font lacks. */
export function textWidth(text: string): number {
  let w = 0
  for (const ch of text) {
    const f = FONT[ch]
    if (!f) return 0
    w += f[0].length + 1
  }
  return Math.max(0, w - 1)
}

